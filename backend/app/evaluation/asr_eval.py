"""Executable specification for a FUTURE Bangla speech-recognition evaluation.

Status: nothing here has been run on real audio. Sathi has no custom ASR model: a provider
supplies the transcript and `callcenter.interpret` turns the words into an amount. There is no
consented audio, no training compute and no speaker-disjoint test set in this repository. This
module defines exactly how a future audio baseline and a fine-tuned model must be compared, so
the result cannot be argued after the fact.

Inputs (CSV or JSON rows):
- manifest row: utt_id, speaker_id, split (train|dev|test), dialect, noise (clean|moderate|heavy),
  reference_text, reference_amount (integer BDT the speaker intended to say).
- hypothesis row: utt_id, system (baseline|fine_tuned|...), text, confidence (may be empty),
  latency_ms.

Hard rules enforced by `validate_manifest`:
- Speaker-disjoint: no speaker appears in both a training and a test/dev split.
- The manifest must not contain the ledger amount of any transaction. A model or prompt that is
  biased with the expected ledger amount would make "exact amount accuracy" meaningless; such a
  column is rejected.
- Every dialect x noise slice that is reported needs at least MIN_UTTERANCES_PER_SLICE test
  utterances from at least MIN_SPEAKERS_PER_SLICE speakers, otherwise it is reported as "too
  small to report" instead of a number.

Metrics per system and slice: WER, CER, exact-amount accuracy, wrong-amount acceptance (the
parser returned a DIFFERENT amount: the dangerous error), abstention (the parser said
"unclear"), p95 latency, with Wilson intervals on the proportions. Typed transcripts or audio
generated by text-to-speech must not be reported as dialect validation.
"""

from __future__ import annotations

import math
import unicodedata
from collections import defaultdict
from typing import Any, Iterable

from app.callcenter.interpret import interpret

MIN_UTTERANCES_PER_SLICE = 100
MIN_SPEAKERS_PER_SLICE = 10
NOISE_LEVELS = ("clean", "moderate", "heavy")
FORBIDDEN_COLUMNS = ("ledger_amount", "expected_amount", "transaction_amount")
# Acceptance gates a fine-tuned model must pass over the baseline on the held-out test split.
GATES = {
    "wrong_amount_acceptance_max": 0.005,
    "exact_amount_accuracy_gain_min_pp": 5.0,
    "abstention_max": 0.30,
    "p95_latency_ms_max": 2500,
    "no_dialect_slice_worse_than_baseline": True,
}


def normalize(text: str) -> str:
    return " ".join(unicodedata.normalize("NFC", text or "").lower().split())


def edit_distance(a: list[str] | str, b: list[str] | str) -> int:
    prev = list(range(len(b) + 1))
    for i, x in enumerate(a, 1):
        cur = [i]
        for j, y in enumerate(b, 1):
            cur.append(min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (x != y)))
        prev = cur
    return prev[-1]


def wer(reference: str, hypothesis: str) -> tuple[int, int]:
    """(word errors, reference words)."""
    ref, hyp = normalize(reference).split(), normalize(hypothesis).split()
    return edit_distance(ref, hyp), len(ref)


def cer(reference: str, hypothesis: str) -> tuple[int, int]:
    ref, hyp = normalize(reference).replace(" ", ""), normalize(hypothesis).replace(" ", "")
    return edit_distance(ref, hyp), len(ref)


def wilson(successes: int, total: int, z: float = 1.96) -> list[float] | None:
    if total <= 0:
        return None
    p = successes / total
    denom = 1 + z * z / total
    centre = (p + z * z / (2 * total)) / denom
    half = z * math.sqrt(p * (1 - p) / total + z * z / (4 * total * total)) / denom
    return [round(max(0.0, centre - half), 4), round(min(1.0, centre + half), 4)]


def percentile(values: list[float], q: float) -> float | None:
    if not values:
        return None
    ordered = sorted(values)
    return ordered[min(len(ordered) - 1, math.ceil(q * len(ordered)) - 1)]


def validate_manifest(rows: list[dict[str, Any]]) -> list[str]:
    """Return a list of problems; an empty list means the manifest may be used."""
    problems = []
    if not rows:
        return ["manifest is empty"]
    for column in FORBIDDEN_COLUMNS:
        if any(column in row for row in rows):
            problems.append(f"column '{column}' must not exist: transcription must never be "
                            "biased with the expected ledger amount")
    splits_by_speaker: dict[str, set[str]] = defaultdict(set)
    for row in rows:
        splits_by_speaker[row["speaker_id"]].add(row["split"])
        if row["split"] not in ("train", "dev", "test"):
            problems.append(f"{row['utt_id']}: unknown split {row['split']!r}")
        if row.get("noise") not in NOISE_LEVELS:
            problems.append(f"{row['utt_id']}: noise must be one of {NOISE_LEVELS}")
    for speaker, splits in splits_by_speaker.items():
        if "train" in splits and splits & {"dev", "test"}:
            problems.append(f"speaker {speaker} appears in train and in dev/test: not "
                            "speaker-disjoint")
    return problems


def _amount_outcome(text: str, confidence: Any) -> tuple[str, str | None]:
    """The production parser, applied AFTER transcription. A parser is not ASR."""
    answer = interpret("", text, confidence)
    return answer.kind, answer.digits or None


def evaluate(manifest: list[dict[str, Any]], hypotheses: Iterable[dict[str, Any]],
             split: str = "test") -> dict[str, Any]:
    problems = validate_manifest(manifest)
    if problems:
        raise ValueError("; ".join(problems))
    reference = {row["utt_id"]: row for row in manifest if row["split"] == split}
    stats: dict[tuple, dict[str, Any]] = {}
    for hyp in hypotheses:
        row = reference.get(hyp["utt_id"])
        if row is None:
            continue
        kind, digits = _amount_outcome(hyp.get("text", ""), hyp.get("confidence") or None)
        for key in ((hyp["system"], "all", "all"), (hyp["system"], row["dialect"], "all"),
                    (hyp["system"], "all", row["noise"]),
                    (hyp["system"], row["dialect"], row["noise"])):
            s = stats.setdefault(key, {"n": 0, "speakers": set(), "we": 0, "wn": 0, "ce": 0,
                                       "cn": 0, "exact": 0, "wrong": 0, "abstain": 0,
                                       "latency": []})
            we, wn = wer(row["reference_text"], hyp.get("text", ""))
            ce, cn = cer(row["reference_text"], hyp.get("text", ""))
            s["n"] += 1
            s["speakers"].add(row["speaker_id"])
            s["we"] += we
            s["wn"] += wn
            s["ce"] += ce
            s["cn"] += cn
            if kind == "amount" and digits == str(row["reference_amount"]):
                s["exact"] += 1
            elif kind == "amount":
                s["wrong"] += 1
            else:
                s["abstain"] += 1
            if hyp.get("latency_ms") not in (None, ""):
                s["latency"].append(float(hyp["latency_ms"]))
    out: dict[str, Any] = {}
    for (system, dialect, noise), s in sorted(stats.items()):
        slice_name = f"{dialect}|{noise}"
        if s["n"] < MIN_UTTERANCES_PER_SLICE or len(s["speakers"]) < MIN_SPEAKERS_PER_SLICE:
            out.setdefault(system, {})[slice_name] = {
                "utterances": s["n"], "speakers": len(s["speakers"]),
                "status": "too small to report"}
            continue
        out.setdefault(system, {})[slice_name] = {
            "utterances": s["n"], "speakers": len(s["speakers"]),
            "wer": round(s["we"] / max(1, s["wn"]), 4), "cer": round(s["ce"] / max(1, s["cn"]), 4),
            "exact_amount_accuracy": {"rate": round(s["exact"] / s["n"], 4),
                                      "ci95": wilson(s["exact"], s["n"])},
            "wrong_amount_acceptance": {"rate": round(s["wrong"] / s["n"], 4),
                                        "ci95": wilson(s["wrong"], s["n"])},
            "abstention": {"rate": round(s["abstain"] / s["n"], 4),
                           "ci95": wilson(s["abstain"], s["n"])},
            "p95_latency_ms": percentile(s["latency"], 0.95),
        }
    return {"split": split, "systems": out, "gates": GATES,
            "status": "NOT RUN ON REAL AUDIO: this repository holds no consented recordings"}


def check_gates(result: dict[str, Any], baseline: str, candidate: str) -> dict[str, Any]:
    """Compare a candidate to the baseline on the overall slice and every reported slice."""
    base, cand = result["systems"][baseline], result["systems"][candidate]
    overall_b, overall_c = base["all|all"], cand["all|all"]
    verdict = {
        "wrong_amount_acceptance_ok": overall_c["wrong_amount_acceptance"]["rate"]
        <= GATES["wrong_amount_acceptance_max"],
        "exact_gain_pp": round(100 * (overall_c["exact_amount_accuracy"]["rate"]
                                      - overall_b["exact_amount_accuracy"]["rate"]), 2),
        "abstention_ok": overall_c["abstention"]["rate"] <= GATES["abstention_max"],
        "p95_latency_ok": (overall_c["p95_latency_ms"] or 0) <= GATES["p95_latency_ms_max"],
    }
    worse = [name for name, c in cand.items()
             if "exact_amount_accuracy" in c and "exact_amount_accuracy" in base.get(name, {})
             and c["exact_amount_accuracy"]["rate"] < base[name]["exact_amount_accuracy"]["rate"]
             and name != "all|all"]
    verdict["slices_worse_than_baseline"] = worse
    verdict["passes"] = (verdict["wrong_amount_acceptance_ok"]
                         and verdict["exact_gain_pp"] >= GATES["exact_amount_accuracy_gain_min_pp"]
                         and verdict["abstention_ok"] and verdict["p95_latency_ok"] and not worse)
    return verdict
